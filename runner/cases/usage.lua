-- 아츠·스펠·【起】 사용과 확정 전 취소

-- 상대 시그니 1체를 대상으로 바니시하는 스펠
local BANISH_SPELL = [[
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_ACTIVATE)
  e1:SetTarget(s.tg)
  e1:SetOperation(s.op)
  c:RegisterEffect(e1)
end
function s.tg(e,tp,eg,ep,ev,re,r,rp,chk)
  if chk==0 then return Duel.IsExistingTarget(Card.IsSigni,tp,0,LOCATION_SZONE,1,nil) end
  Duel.SelectTarget(tp,Card.IsSigni,tp,0,LOCATION_SZONE,1,1,nil)
end
function s.op(e,tp)
  ORDER = (ORDER or '') .. 'S'
  local tc=Duel.GetFirstTarget()
  if tc and tc:IsRelateToEffect(e) then Duel.Banish(tc) end
end
]]

-- 1장 뽑는 아츠
local DRAW_ARTS = [[
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_ACTIVATE)
  e1:SetOperation(function(e,tp) Duel.Draw(tp,1) end)
  c:RegisterEffect(e1)
end
]]

local function setup(t)
  t:lrig(1, 3, 9, {"タマ"})
  t:signi(100, 5000)
  t:signi(101, 3000, COLOR_RED)
  t:card{cid = 400, type = TYPE_SPELL, cost = "{W}"}
  t:script(400, BANISH_SPELL)
  t:card{cid = 401, type = TYPE_ARTS, timing = TIMING_ATTACK}
  t:script(401, DRAW_ARTS)
end

local function stock(t)
  t:fill(100, 0, "main_deck", 10)
  t:fill(100, 1, "main_deck", 10)
end

case("use: 스펠은 코스트 → 대상 → 효과 → 트래시", "faq.txt 「スペルの使用手順」", function(t)
  setup(t)
  t:start()
  stock(t)
  t:put(1, 0, "lrig_center")
  local spell = t:put(400, 0, "hand")
  local white = t:put(100, 0, "ena")
  local target = t:put(100, 1, "signi_left")
  t:begin(0, PHASE_MAIN)
  t:expect(t:wait(HINT_MAIN))
  local act = t:action(ACT_USE, spell)
  t:expect(act ~= nil)
  t:expect(t:answer(act))
  t:expect(t:wait(HINT_PAY_ENA))
  t:expect(t:request().cancelable)
  t:expect(t:answer(white))
  t:expect(t:wait(HINT_TARGET))
  local o = t:request().options
  t:expect(#o == 1 and o[1] == target)
  t:expect(t:answer(target))
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:is_in(target, 1, "ena"))
  t:expect(t:is_in(spell, 0, "trash"))
  t:expect(t:is_in(white, 0, "trash"))
  t:expect(t:saw(HINT_CUTIN), "상대에게 컷인 창이 열렸다(always_ask)")
end)

