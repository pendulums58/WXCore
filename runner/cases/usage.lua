case("use: 【起】 에나 코스트를 내고 효과를 처리한다", "용어집: 起動能力", function(t)
  setup(t)
  t:signi(403, 5000)
  t:script(403, [[
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_IGNITION)
  e1:SetRange(LOCATION_SZONE)
  e1:SetEnaCost('{R}')
  e1:SetOperation(function(e,tp)
    local c=e:GetHandler()
    -- [まで] 턴 종료 시까지, 대상 고정
    local e2=Effect.CreateEffect(c)
    e2:SetType(EFFECT_TYPE_SINGLE)
    e2:SetCode(EFFECT_UPDATE_POWER)
    e2:SetValue(3000)
    e2:SetReset(RESET_PHASE+PHASE_END)
    c:RegisterEffect(e2)
  end)
  c:RegisterEffect(e1)
end
]])
  for _, has_red in ipairs{false, true} do
    t:start()
    stock(t)
    t:put(1, 0, "lrig_center")
    local s = t:put(403, 0, "signi_left")
    t:put(100, 0, "ena")
    local red = has_red and t:put(101, 0, "ena")
    t:begin(0, PHASE_MAIN)
    t:expect(t:wait(HINT_MAIN))
    local act = t:action(ACT_ABILITY, s)
    if not has_red then
      t:expect(act == nil, "적 에나가 없다")
    else
      t:expect(act ~= nil)
      t:expect(t:answer(act))
      t:expect(t:wait(HINT_PAY_ENA))
      t:expect(t:answer(red))
      t:expect(t:wait(HINT_MAIN))
      t:expect(t:power(s) == 8000)
    end
  end
end)

