  t:expect(t:coins(0) == 0 and t:count(0, "hand") == 1)
end)

case("難攻不落: ②는 【チャーム】 수만큼 뽑고 【エナチャージ１】", "WDK12-007", function(t)
  wd(t)
  local arts = t:put(N[7], 0, "lrig_deck")
  local h1, h2 = t:put(N[13], 0, "signi_left"), t:put(N[14], 0, "signi_center")
  local c1, c2 = t:put(GREEN, 0, "hand"), t:put(GREEN, 0, "hand")
  t:attach(c1, h1, "charm")
  t:attach(c2, h2, "charm")
  ena(t, 1)
  main(t)
  use(t, arts)
  pick(t, HINT_MODE, 1)
  pay(t, 1)
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:is_in(c1, 0, "trash") and t:is_in(c2, 0, "trash"))
  t:expect(t:count(0, "hand") == 2 and t:count(0, "ena") == 2)
end)

case("難攻不落: ベット하면 둘 다. ①로 붙인 시그니도 바니시되지 않는 능력을 얻는다", "WDK12-007 FAQ 1", function(t)
  wd(t)
  t:add_coin(0, 2)
  local arts = t:put(N[7], 0, "lrig_deck")
  local h, other = t:put(N[16], 0, "signi_left"), t:put(N[13], 0, "signi_center")
  local ch = t:put(N[17], 0, "trash")
  ena(t, 1)
  t:begin(1, PHASE_ATTACK)
  t:expect(t:wait(HINT_DEFENSE))
  use(t, arts)
  pick(t, HINT_BET, 1)
  pay(t, 1)
  pick(t, HINT_TARGET, ch)
  pick(t, HINT_TARGET, h)
  t:expect(t:wait(HINT_DEFENSE))
  t:expect(t:coins(0) == 0 and t:keyword(h, EFFECT_CANNOT_BANISH) and not t:keyword(other, EFFECT_CANNOT_BANISH), "상대 턴 동안")
  t:expect(t:is_in(ch, 0, "trash") and t:count(0, "hand") == 1, "②로 방금 붙인 【チャーム】을 트래시에 두고 1장")
end)

case("化学分解: 상대 장에 키가 있으면 추가로 뽑고 【エナチャージ１】. 시그니가 없어도 쓸 수 있다", "WDK12-008 FAQ 2", function(t)
  for _, c in ipairs{{true, true}, {false, true}, {true, false}} do
    wd(t)
    local arts = t:put(N[8], 0, "lrig_deck")
    if c[1] then t:put(N[10], 1, "key") end
    local x = c[2] and t:put(BIG, 1, "signi_left")
    ena(t, 1)
    main(t)
    use(t, arts)
    pay(t, 1)
    if x then pick(t, HINT_TARGET, x) end
    t:expect(t:wait(HINT_MAIN))
    if x then t:expect(t:is_in(x, 1, "ena")) end
    t:expect(t:count(0, "hand") == (c[1] and 1 or 0) and t:count(0, "ena") == (c[1] and 1 or 0))
  end
end)

case("双撃の記憶　リル: 센터 루리그와 같은 색 시그니면 패에, 아니면 덱 위에 그대로", "WDK12-009 FAQ 3·5", function(t)
  for _, green in ipairs{true, false} do
    wd(t)
    t:put(N[9], 0, "key")
    local top = t:put(green and N[16] or OPP, 0, "main_deck")
    t:begin(0, PHASE_GROW)  -- 그로우할 루리그가 없으면 바로 메인 페이즈
    t:expect(t:wait(HINT_MAIN))
    t:expect(t:is_in(top, 0, green and "hand" or "main_deck"))
  end
end)

case("双撃の記憶　リル: 키를 루리그 트래시에 두고 코인 2개", "WDK12-009", function(t)
  wd(t)
  local k = t:put(N[9], 0, "key")
  main(t)
  t:expect(t:answer(ability(t, k, 0)))
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:is_in(k, 0, "lrig_trash") and t:coins(0) == 2)
end)

case("羅菌 ビオチン: 내 턴에만 【チャーム】 시그니 ＋3000. 자신도 포함", "WDK12-013 FAQ 1", function(t)
  for p = 0, 1 do
    wd(t)
    local h = t:put(N[13], 0, "signi_left")
    t:attach(t:put(GREEN, 0, "hand"), h, "charm")
    main(t, p)
    t:expect(t:power(h) == (p == 0 and 11000 or 8000))
  end
end)

case("羅菌 コッパー: 【チャーム】이 붙어 있으면 ＋5000·【ランサー】", "WDK12-014", function(t)
  wd(t)
  local h = t:put(N[14], 0, "signi_left")
  main(t)
  t:expect(t:power(h) == 7000 and not t:keyword(h, EFFECT_LANCER))
  t:attach(t:put(GREEN, 0, "hand"), h, "charm")
  t:expect(t:power(h) == 12000 and t:keyword(h, EFFECT_LANCER))
end)

case("羅菌 カーボ: 어택하면 《緑》와 【チャーム】으로 업", "WDK12-015", function(t)
  wd(t)
  local h = t:put(N[15], 0, "signi_left")
  local ch = t:put(GREEN, 0, "hand")
  t:attach(ch, h, "charm")
  ena(t, 1)
  t:begin(0, PHASE_ATTACK)
  pick(t, HINT_ATTACK_SIGNI, h)
  pick(t, HINT_SCRIPT, 1)
  pay(t, 1)
  t:expect(t:wait(HINT_SELECT))
  t:expect(t:answer(ch))
  t:expect(t:wait(HINT_ATTACK_SIGNI))
  t:expect(t:is_in(ch, 0, "trash") and t:flags(h) & CF_DOWN == 0, "업")
end)

case("羅菌 センイ: 다른 시그니에 강제로 【チャーム】", "WDK12-017 FAQ 1", function(t)
