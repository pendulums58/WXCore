-- WDK12 メル 구축덱 카드 스크립트 케이스. 근거는 카드별 FAQ(cards.json)

local N = {}
local GREEN, OPP, MID, BIG = 200000, 101000, 101700, 102000

local function wd(t, center)
  t:start{db = true, seed = 1}
  for i = 1, 22 do N[i] = t:no(("WDK12-%03d"):format(i)) end
  t:signi(GREEN, 1000, COLOR_GREEN, 1)
  t:signi(OPP, 3000, COLOR_RED, 1)
  t:signi(MID, 7000, COLOR_RED, 3)
  t:signi(BIG, 9000, COLOR_RED, 4)
  t:fill(GREEN, 0, "main_deck", 15)
  t:fill(OPP, 1, "main_deck", 15)
  t:fill(GREEN, 0, "life_cloth", 5)
  t:fill(OPP, 1, "life_cloth", 5)
  t:put(N[1], 1, "lrig_center")
  return t:put(N[center or 1], 0, "lrig_center")
end

local function main(t, p)
  t:begin(p or 0, PHASE_MAIN)
  t:expect(t:wait(HINT_MAIN))
end

local function ena(t, n, cid)
  for _ = 1, n do t:put(cid or GREEN, 0, "ena") end
end

local function pick(t, hint, ...)
  t:expect(t:wait(hint), "힌트 " .. hint)
  t:expect(t:answer(...))
end

local function pay(t, n)
  t:expect(t:wait(HINT_PAY_ENA), "에나 " .. n)
  t:expect(t:answer(table.unpack(t:cards(0, "ena"), 1, n)))
end

local function use(t, c) t:expect(t:answer(t:action(ACT_USE, c))) end
local function ability(t, c, n) return t:action(ACT_ABILITY, c, n or 0) end

case("メル＝ヴェスパー: 【エナチャージ２】으로 놓인 시그니도 패에", "WDK12-001 FAQ 1", function(t)
  wd(t, 2)
  local g = t:put(N[1], 0, "lrig_deck")
  local top = t:put(N[16], 0, "main_deck")
  t:begin(0, PHASE_GROW)
  pick(t, HINT_GROW, g)
  pick(t, HINT_TARGET, top)
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:is_in(top, 0, "hand") and t:count(0, "ena") == 1)
end)

case("メル＝ヴェスパー: 트래시의 ＜微菌＞을 【チャーム】으로. 《ターン１回》", "WDK12-001", function(t)
  local lc = wd(t)
  local h = t:put(N[11], 0, "signi_left")
  local ch = t:put(N[16], 0, "trash")
  main(t)
  t:expect(t:answer(ability(t, lc, 0)))
  pick(t, HINT_TARGET, ch)
  pick(t, HINT_TARGET, h)
  t:expect(t:wait(HINT_MAIN))
  t:expect(not t:is_in(ch, 0, "trash") and t:power(h) == 15000, "ヨウサン 자신도 ＋3000")
  t:expect(ability(t, lc, 0) == nil, "《ターン１回》")
end)

case("メル＝ヴェスパー: 코인 1개로 이 턴 「낸 시그니의 파워 이하를 바니시」. 《ゲーム１回》", "WDK12-001 FAQ 2", function(t)
  local lc = wd(t)
  t:add_coin(0, 2)
  local s = t:put(N[14], 0, "hand")
  local a, b = t:put(MID, 1, "signi_left"), t:put(BIG, 1, "signi_center")
  main(t)
  t:expect(t:answer(ability(t, lc, 1)))
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:coins(0) == 1 and ability(t, lc, 1) == nil, "《ゲーム１回》")
  t:expect(t:answer(t:action(ACT_PLAY, s, "signi_left")))
  pick(t, HINT_TARGET, a)
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:is_in(a, 1, "ena") and t:is_in(b, 1, "signi_center"), "7000 이하만")
end)

case("メル＝バラライカソニック: 코인 1개로 1장 뽑는다", "WDK12-003", function(t)
  wd(t, 4)
