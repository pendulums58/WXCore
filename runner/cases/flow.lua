-- 턴 진행·룰 처리·트리거

-- 양쪽에 레벨 3·리미트 9 루리그(타입 タマ), 시그니 두 종
local function base(t)
  t:lrig(1, 3, 9, {"タマ"})
  t:signi(100, 5000)
  t:signi(101, 3000)
end

-- 양쪽 덱을 채운다. 덱이 비어 있으면 트래시에 카드가 들어가는 순간 리프레시가 일어난다
local function stock(t, n)
  t:fill(100, 0, "main_deck", n or 10)
  t:fill(100, 1, "main_deck", n or 10)
end

local function draw_on(event)
  return ([[
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_SINGLE+EFFECT_TYPE_TRIGGER_F)
  e1:SetCode(%s)
  e1:SetOperation(function(e,tp) Duel.Draw(tp,1) end)
  c:RegisterEffect(e1)
end
]]):format(event)
end

local function deck40(first, n)
  local d = {}
  for i = 0, 39 do d[#d + 1] = first + i % (n or 1) end
  return d
end

