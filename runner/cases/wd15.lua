-- WD15 遊月 구축덱 카드 스크립트 케이스. 근거는 카드별 FAQ(cards.json)

local N = {}

-- 200: 적 ＜龍獣＞ 레벨 2, 201: 적 ＜鉱石＞ 레벨 1
-- 101: 상대 녹 레벨 1 파워 1000, 102: 상대 녹 레벨 3 파워 15000, 103: 상대 백(루리그와 다른 색), 104: 무색
-- 상대 루리그(300): 녹
local function wd(t, center)
  t:start{db = true, seed = 1}
  for i = 1, 24 do
    local no = ("%03d"):format(i)
    N[no] = t:no("WD15-" .. no)
  end
  t:card{cid = 200, power = 3000, level = 2, classes = {"精生：龍獣"}, color = COLOR_RED}
  t:card{cid = 201, power = 1000, level = 1, classes = {"精羅：鉱石"}, color = COLOR_RED}
  t:signi(101, 1000, COLOR_GREEN, 1)
  t:signi(102, 15000, COLOR_GREEN, 3)
  t:signi(103, 1000, COLOR_WHITE, 1)
  t:signi(104, 1000, 0, 1)
  t:lrig(300, 4, 11, {"タマ"}, COLOR_GREEN)
  t:fill(201, 0, "main_deck", 10)
  t:fill(101, 1, "main_deck", 10)
  t:fill(201, 0, "life_cloth", 5)
  t:fill(101, 1, "life_cloth", 5)
  t:put(300, 1, "lrig_center")
  return t:put(N[center or "001"], 0, "lrig_center")
end

local function main(t, p)
  t:begin(p or 0, PHASE_MAIN)
  t:expect(t:wait(HINT_MAIN))
end

local function has(list, x)
  for _, v in ipairs(list) do if v == x then return true end end
  return false
end

local function ena(t, n, cid, p)
  for _ = 1, n do t:put(cid or 201, p or 0, "ena") end
  return t:cards(p or 0, "ena")
end

local function zone(t)
  t:expect(t:wait(HINT_ZONE))
  t:expect(t:answer(t:request().options[1]))
end

local function pay(t, n)
  t:expect(t:wait(HINT_PAY_ENA))
  t:expect(t:request().min == n, "코스트 " .. n)
  t:expect(t:answer(table.unpack(t:cards(t:request().player, "ena"), 1, n)))
end

local function use(t, card, n)
  t:expect(t:answer(t:action(ACT_USE, card)))
  if n and n > 0 then pay(t, n) end
end

local function play(t, c, z) t:expect(t:answer(t:action(ACT_PLAY, c, z or "signi_left"))) end

local function burst(t, no, setup)
  wd(t, "001")
  t:put(N[no], 0, "life_cloth")
  if setup then setup() end
  local a = t:put(102, 1, "signi_left")
  t:begin(1, PHASE_ATTACK)
  t:expect(t:wait(HINT_ATTACK_SIGNI))
  t:expect(t:answer(a))
  t:expect(t:wait(HINT_LIFEBURST))
  t:expect(t:answer(1))
end

-- 자기 효과로 상대 에나 1~2장을 트래시에(捲火重来)
local function burn(t, n)
  local arts = t:put(N["009"], 0, "lrig_deck")
  ena(t, 2)
  main(t)
  use(t, arts, 2)
  t:expect(t:wait(HINT_TARGET))
  t:expect(t:answer(table.unpack(t:cards(1, "ena"), 1, n)))
end

