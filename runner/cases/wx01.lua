  local sp, a, late = t:put(N[50], 0, "hand"), t:put(GS, 0, "signi_left"), t:put(GS, 0, "hand")
  t:put(GS, 0, "ena")
  main(t)
  use(t, sp)
  pay(t, 1)
  t:expect(t:wait(HINT_MAIN))
  play(t, late, "signi_center")
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:power(a) == 7000 and t:power(late) == 2000)
end)

