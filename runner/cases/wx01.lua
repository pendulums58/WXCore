case("逆出: 에나의 시그니를 장에. 레벨을 넘으면 못 낸다", "WX01-099 FAQ 1·2", function(t)
  for _, c in ipairs{{GS, true}, {BIG, false}} do
    wd(t, 20)
    local sp, x = t:put(N[99], 0, "hand"), t:put(c[1], 0, "ena")
    t:put(GS, 0, "ena")
    main(t)
    use(t, sp)
    t:expect(t:wait(HINT_PAY_ENA))
    t:expect(t:answer(t:cards(0, "ena")[2]))
    pick(t, HINT_TARGET, x)
    if c[2] then zone(t) end
    t:expect(t:wait(HINT_MAIN))
    t:expect(t:is_in(x, 0, "ena") == not c[2])
  end
end)

