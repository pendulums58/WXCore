-- WD18 メル 구축덱 카드 스크립트 케이스 + 【アクセ】 룰. 근거는 카드별 FAQ(cards.json)·용어집: アクセ

local N = {}
local CHOURI, GREEN, OPP, BIG = 200000, 201000, 101000, 102000

local function wd(t, center)
  t:start{db = true, seed = 1}
  for i = 1, 18 do
    local no = ("%03d"):format(i)
    N[no] = t:no("WD18-" .. no)
  end
  t:card{cid = CHOURI, power = 4000, level = 2, classes = {"精械：調理"}, color = COLOR_GREEN}
  t:signi(GREEN, 1000, COLOR_GREEN, 1)
  t:signi(OPP, 1000, COLOR_RED, 1)
  t:signi(BIG, 15000, COLOR_RED, 3)
  t:fill(GREEN, 0, "main_deck", 10)
  t:fill(OPP, 1, "main_deck", 10)
  t:fill(GREEN, 0, "life_cloth", 5)
  t:fill(OPP, 1, "life_cloth", 5)
  t:put(N["001"], 1, "lrig_center")
  return t:put(N[center or "001"], 0, "lrig_center")
end

local function main(t, p)
  t:begin(p or 0, PHASE_MAIN)
  t:expect(t:wait(HINT_MAIN))
end

local function acce(t, no, host)
  local a = t:put(N[no], 0, "ena")
  t:attach(a, host, true)
  return a
end

local function use(t, c)
  t:expect(t:answer(t:action(ACT_USE, c)))
end

local function ability(t, c, n) return t:action(ACT_ABILITY, c, n or 0) end

-- 【ライフバースト】를 쓰고 첫 요청까지
local function burst(t, c)
  t:move(c, 0, "life_cloth")
  local a = t:put(BIG, 1, "signi_left")
  t:begin(1, PHASE_ATTACK)
  t:expect(t:wait(HINT_ATTACK_SIGNI))
  t:expect(t:answer(a))
  t:expect(t:wait(HINT_LIFEBURST))
  t:expect(t:answer(1))
end

