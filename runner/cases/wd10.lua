-- WD10 紅タマ 구축덱 카드 스크립트 케이스 + 크로스·헤븐 룰. 근거는 카드별 FAQ(cards.json)·용어집·faq.txt

local N = {}

-- 200: 적 ＜ウェポン＞ 레벨 1, 201: 적 ＜鉱石＞ 레벨 1
-- 101: 상대 파워 2000, 102: 상대 파워 8000, 103: 상대 파워 12000, 104: 상대 파워 15000
local function wd(t, center_no)
  t:start{db = true, seed = 1}
  for i = 1, 18 do
    local no = ("%03d"):format(i)
    N[no] = t:no("WD10-" .. no)
  end
  t:card{cid = 200, power = 1000, level = 1, classes = {"精武：ウェポン"}, color = COLOR_RED}
  t:card{cid = 201, power = 1000, level = 1, classes = {"精羅：鉱石"}, color = COLOR_RED}
  t:signi(101, 2000, COLOR_GREEN, 1)
  t:signi(102, 8000, COLOR_GREEN, 1)
  t:signi(103, 12000, COLOR_GREEN, 1)
  t:signi(104, 15000, COLOR_GREEN, 1)
  t:fill(201, 0, "main_deck", 10)
  t:fill(101, 1, "main_deck", 10)
  t:fill(201, 0, "life_cloth", 5)
  t:fill(101, 1, "life_cloth", 5)
  t:put(N[center_no or "002"], 0, "lrig_center")
  t:put(N["002"], 1, "lrig_center")
end

local function main(t)
  t:begin(0, PHASE_MAIN)
  t:expect(t:wait(HINT_MAIN))
end

local function attack(t, c)
  t:expect(t:wait(HINT_ATTACK_SIGNI))
  t:expect(t:answer(c))
end

local function ena(t, n)
  for _ = 1, n do t:put(200, 0, "ena") end
  return t:cards(0, "ena")
end

local function has(list, x)
  for _, v in ipairs(list) do if v == x then return true end end
  return false
end

