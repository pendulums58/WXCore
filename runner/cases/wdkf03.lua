-- ── 08 イレイズ・ルフラン(ベット) ──

local BUFF = [[
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_SINGLE)
  e1:SetCode(EFFECT_UPDATE_POWER)
  e1:SetRange(LOCATION_SZONE)
  e1:SetValue(2000)
  c:RegisterEffect(e1)
end
]]

local function erase(t, bet)
  t:script(103, BUFF)
  f03(t, "01")
  t:card{cid = 103, power = 1000, level = 1}
  local arts = t:put(N["08"], 0, "lrig_deck")
  t:put(100, 0, "ena")
  t:add_coin(0, 1)
  local s1, s2 = t:put(103, 1, "signi_left"), t:put(103, 1, "signi_center")
  main(t)
  t:expect(t:answer(t:action(ACT_USE, arts)))
  t:expect(t:wait(HINT_PAY_ENA))
  t:expect(t:answer(t:cards(0, "ena")[1]))
  t:expect(t:wait(HINT_BET), "코인이 있으면 ベット할지 묻는다")
  t:expect(t:answer(bet and 1 or 0))
  return s1, s2
end

