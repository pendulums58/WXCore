-- WDK-F03 タマヨリヒメ 카드 스크립트 케이스. 근거는 카드별 FAQ(cards.json)

local N = {}

-- 100: 흰 시그니(遊具 아님, 덱 채우기), 101: 상대 흰 시그니, 102: 상대 시그니(레벨 4)
local function f03(t, center_no, opts)
  opts = opts or {}
  t:start{db = true, seed = opts.seed or 1}
  for i = 1, 20 do
    local no = ("%02d"):format(i)
    N[no] = t:no("WDK-F03-" .. no)
  end
  t:card{cid = 100, power = 1000, level = 1, classes = {"精武：アーム"}, color = COLOR_WHITE}
  t:card{cid = 101, power = 1000, level = 1, classes = {"奏羅：宇宙"}, color = COLOR_WHITE}
  t:card{cid = 102, power = 12000, level = 4, classes = {"奏羅：宇宙"}, color = COLOR_WHITE}
  if not opts.no_deck then t:fill(100, 0, "main_deck", 10) end
  t:fill(101, 1, "main_deck", 10)
  t:fill(101, 0, "life_cloth", 5)
  t:fill(101, 1, "life_cloth", 5)
  local center = t:put(N[center_no or "01"], 0, "lrig_center")
  t:put(t:no("WXDi-D01-004"), 1, "lrig_center")  -- 상대 센터 Lv3
  return center
end

local function main(t)
  t:begin(0, PHASE_MAIN)
  t:expect(t:wait(HINT_MAIN))
end

local function contains(list, x)
  for _, v in ipairs(list) do if v == x then return true end end
  return false
end

