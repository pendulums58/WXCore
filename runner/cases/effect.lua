-- 효과 모델: 레이어, 고정/동적 대상, 리셋, 능력 획득·상실, 이노센스, 조커

-- WXDi-P16-008 《扉の俯瞰者　タウィル＝トレ》 흉내: 【常】あなたの白のシグニのパワーを＋1000する。
local TAWIL = [[
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】: 나중에 나온 시그니도 받는다
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD)
  e1:SetCode(EFFECT_UPDATE_POWER)
  e1:SetRange(LOCATION_LRIG)
  e1:SetTargetRange(LOCATION_SZONE,0)
  e1:SetTarget(function(e,c) return c:IsColor(COLOR_WHITE) end)
  e1:SetValue(1000)
  c:RegisterEffect(e1)
end
]]

-- 【常】このシグニのパワーは＋(레벨×1000)
local SELF_BUFF = [[
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】 자기 자신
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_SINGLE)
  e1:SetCode(EFFECT_UPDATE_POWER)
  e1:SetRange(LOCATION_SZONE)
  e1:SetValue(function(e,c) return c:GetLevel()*1000 end)
  c:RegisterEffect(e1)
end
]]

local END = RESET_PHASE | PHASE_END

case("power: ＋/－ 수정은 합산", "설계: 레이어 5", function(t)
  t:signi(100, 5000)
  t:start()
  local c = t:put(100, 0, "signi_left")
  t:single(c, EFFECT_UPDATE_POWER, 3000, 0)
  t:single(c, EFFECT_UPDATE_POWER, -1000, 1)
  t:expect(t:power(c) == 7000)
end)

