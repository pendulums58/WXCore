case("joker: 고정 수정과 얻은 능력은 사라지고 상태는 남는다", "WX17-001 FAQ 8·9", function(t)
  t:signi(100, 5000, COLOR_WHITE, 2)
  t:signi(102, 12000, COLOR_RED, 4)
  t:script(102, SELF_BUFF)
  t:start()
  local c = t:put(100, 0, "signi_left")
  t:set_flags(c, CF_DOWN)
  t:single(c, EFFECT_UPDATE_POWER, -8000, 1)
  t:grant(c, EFFECT_UPDATE_POWER, 3000, 0)
  t:copy(c, 102, 0, END)
  t:expect(t:text(c) == 102)
  t:expect(t:color(c) == COLOR_RED)
  t:expect(t:level(c) == 4)
  t:expect(t:power(c) == 16000, "12000 + 복사한 【常】 4000")
  t:expect(t:flags(c) & CF_DOWN ~= 0)
end)

