case("script: math.random은 코어 PRNG를 쓴다", "설계: 결정론", function(t)
  local function roll(seed)
    t:signi(104, 1000)
    t:script(104, "local s,id=GetID()\nfunction s.initial_effect(c) ROLLED=math.random(1000000) end")
    t:start{seed = seed}
    t:put(104, 0, "hand")
    return t:global("ROLLED")
  end
  t:expect(roll(5) == roll(5))
  t:expect(roll(5) ~= roll(6))
end)
