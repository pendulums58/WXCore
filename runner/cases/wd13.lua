-- WD13 白タマ 구축덱 카드 스크립트 케이스 + 「効果を受けない」·그로우 조건. 근거는 카드별 FAQ(cards.json)·용어집

local N = {}

-- 200: 백 레벨 1(클래스 없음), 201: 백 ＜アーム＞ 레벨 1, 202: 백 ＜天使＞ 레벨 1, 203: 백 ＜迷宮＞, 204: 흑 ＜毒牙＞
-- 101: 상대 파워 1000, 102: 상대 파워 20000
local function wd(t, center, opp)
  t:start{db = true, seed = 1}
  for i = 1, 25 do
    local no = ("%03d"):format(i)
    N[no] = t:no("WD13-" .. no)
  end
  t:signi(200, 1000, COLOR_WHITE, 1)
  t:card{cid = 201, power = 1000, level = 1, classes = {"精武：アーム"}, color = COLOR_WHITE}
  t:card{cid = 202, power = 1000, level = 1, classes = {"精像：天使"}, color = COLOR_WHITE}
  t:card{cid = 203, power = 1000, level = 1, classes = {"精械：迷宮"}, color = COLOR_WHITE}
  t:card{cid = 204, power = 1000, level = 1, classes = {"精生：毒牙"}, color = COLOR_BLACK}
  t:signi(101, 1000, COLOR_GREEN, 1)
  t:signi(102, 20000, COLOR_GREEN, 1)
  t:fill(200, 0, "main_deck", 10)
  t:fill(101, 1, "main_deck", 10)
  t:fill(200, 0, "life_cloth", 5)
  t:fill(101, 1, "life_cloth", 5)
  t:put(opp or N["003"], 1, "lrig_center")
  return t:put(N[center or "003"], 0, "lrig_center")
end

local function main(t, p)
  t:begin(p or 0, PHASE_MAIN)
  t:expect(t:wait(HINT_MAIN))
end

local function has(list, x)
  for _, v in ipairs(list) do if v == x then return true end end
  return false
end

local function ena(t, n, p)
  for _ = 1, n do t:put(200, p or 0, "ena") end
  return t:cards(p or 0, "ena")
end

local function zone(t)
  t:expect(t:wait(HINT_ZONE))
  t:expect(t:answer(t:request().options[1]))
end

local function pay(t, n)
  t:expect(t:wait(HINT_PAY_ENA))
  local e = t:cards(t:request().player, "ena")
  t:expect(t:request().min == n, "코스트 " .. n)
  t:expect(t:answer(table.unpack(e, 1, n)))
end

local function use_trigger(t)
  t:expect(t:wait(HINT_USE_TRIGGER))
  t:expect(t:answer(1))
end

