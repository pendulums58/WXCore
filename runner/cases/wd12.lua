  local j = t:put(N["008"], 0, "lrig_deck")
  t:begin(0, PHASE_ENA)
  t:expect(t:wait(HINT_ENA_CHARGE))
  t:expect(t:answer(k))  -- 에나 대신 루리그 덱으로(용어집: レゾナ 3)
  t:expect(t:wait(HINT_SELECT))
  t:expect(not has(t:request().options, k), "레벨 4")
