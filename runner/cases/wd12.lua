    t:expect(t:answer(e))
    t:expect(t:wait(HINT_SCRIPT))
    t:expect(t:answer(1))
    zone(t)
    t:wait(HINT_ATTACK_LRIG)
    t:expect(t:flags(m) & CF_DOWN ~= 0 and not t:is_in(e, 0, "ena"))
  end
end)

