-- 【出】《黒》: 낸 뒤 코스트를 내고 대상까지
local function play_pay(t, c, e)
  t:expect(t:answer(t:action(ACT_PLAY, c, "signi_left")))
  t:expect(t:wait(HINT_USE_TRIGGER))
  t:expect(t:answer(1))
  t:expect(t:wait(HINT_PAY_ENA))
  t:expect(t:answer(e))
  t:expect(t:wait(HINT_TARGET))
end

case("クロハ: 코스트로 트래시에 간 레벨 2 이하 흑 시그니도 낼 수 있다", "WD11-009 FAQ 1", function(t)
  wd(t)
  local k = t:put(N["009"], 0, "hand")
  local e = t:put(202, 0, "ena")
  local big = t:put(N["011"], 0, "trash")  -- 레벨 3
  main(t)
  play_pay(t, k, e)
  t:expect(not has(t:request().options, big))
  t:expect(t:answer(e))
  t:expect(t:wait(HINT_ZONE))
  t:expect(t:answer(t:request().options[1]))
