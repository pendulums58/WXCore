local function insect(t, with_resona)
  wd(t)
  local sp = t:put(N["018"], 0, "hand")
  local e = t:put(201, 0, "ena")
  local a = t:put(202, 0, "trash")
  if with_resona then t:put(N["008"], 0, "signi_left") end
  main(t)
  t:expect(t:answer(t:action(ACT_USE, sp)))
  t:expect(t:wait(HINT_PAY_ENA))
  t:expect(t:answer(e))
  t:expect(t:wait(HINT_TARGET))
  t:expect(t:answer(e))  -- 코스트로 낸 카드
  return e, a
end

case("ゲット・インセクト: 코스트로 낸 카드도 대상. 레조나가 있으면 1장 더", "WD11-018 FAQ 1", function(t)
  local e, a = insect(t, false)
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:is_in(e, 0, "hand") and t:is_in(a, 0, "trash"))
  e, a = insect(t, true)
  t:expect(t:wait(HINT_TARGET))
  t:expect(t:answer(a))
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:is_in(e, 0, "hand") and t:is_in(a, 0, "hand"))
end)
