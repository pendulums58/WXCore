-- WD11 ミュウ 구축덱 카드 스크립트 케이스. 근거는 카드별 FAQ(cards.json)

local N = {}

-- 201: 흑 ＜凶蟲＞ 레벨 1, 202: 흑 ＜凶蟲＞ 레벨 2, 203: 흑 ＜古代兵器＞ 레벨 1
-- 101: 상대 파워 5000 레벨 1, 102: 상대 파워 15000 레벨 3
local function wd(t)
  t:start{db = true, seed = 1}
  for i = 1, 18 do
    local no = ("%03d"):format(i)
    N[no] = t:no("WD11-" .. no)
  end
  t:card{cid = 201, power = 1000, level = 1, classes = {"精生：凶蟲"}, color = COLOR_BLACK}
  t:card{cid = 202, power = 3000, level = 2, classes = {"精生：凶蟲"}, color = COLOR_BLACK}
  t:card{cid = 203, power = 1000, level = 1, classes = {"精械：古代兵器"}, color = COLOR_BLACK}
  t:signi(101, 5000, COLOR_GREEN, 1)
  t:signi(102, 15000, COLOR_GREEN, 3)
  t:fill(203, 0, "main_deck", 10)
  t:fill(101, 1, "main_deck", 10)
  t:fill(203, 0, "life_cloth", 5)
  t:fill(101, 1, "life_cloth", 5)
  t:put(N["001"], 1, "lrig_center")
  return t:put(N["001"], 0, "lrig_center")
end

local function main(t)
  t:begin(0, PHASE_MAIN)
  t:expect(t:wait(HINT_MAIN))
end

local function has(list, x)
  for _, v in ipairs(list) do if v == x then return true end end
  return false
end

local function resona(t, r)
  t:expect(t:answer(t:action(ACT_RESONA, r)))
  t:expect(t:wait(HINT_RESONA))
end

case("ミュウ=イマゴ: 【起】다운으로 트래시의 ＜凶蟲＞를 패에", "WD11-001", function(t)
  local center = wd(t)
  local a = t:put(201, 0, "trash")
  local b = t:put(203, 0, "trash")
  main(t)
  t:expect(t:answer(t:action(ACT_ABILITY, center)))
  t:expect(t:wait(HINT_TARGET))
  t:expect(not has(t:request().options, b))
  t:expect(t:answer(a))
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:is_in(a, 0, "hand") and t:flags(center) & CF_DOWN ~= 0)
  t:expect(t:action(ACT_ABILITY, center) == nil)
end)

case("ムカデス: 출현 조건으로 트래시한 레벨 합계 × －2000, 이마고와 순서를 고른다", "WD11-007 FAQ 1, WD11-001 FAQ 1", function(t)
  wd(t)
  local r = t:put(N["007"], 0, "lrig_deck")
  local a = t:put(201, 0, "signi_left")
  local b = t:put(202, 0, "signi_center")
  local x = t:put(102, 1, "signi_center")
  main(t)
  resona(t, r)
  t:expect(t:answer(a, b))
  t:expect(t:wait(HINT_ZONE))
  t:expect(t:answer(t:request().options[1]))
  t:expect(t:wait(HINT_TRIGGER_ORDER))
  t:expect(#t:request().options == 2)
  t:expect(t:wait(HINT_TARGET))
  t:expect(t:answer(x))
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:power(x) == 9000, "레벨 1 + 2 = 3 → －6000")
  t:expect(t:count(0, "ena") == 1)
end)

local function yasu(t)
  local r = t:put(N["008"], 0, "lrig_deck")
  return {
    r = r,
    h1 = t:put(201, 0, "hand"), h2 = t:put(202, 0, "hand"), hx = t:put(203, 0, "hand"),
    e1 = t:put(201, 0, "ena"), e2 = t:put(201, 0, "ena"), e3 = t:put(201, 0, "ena"),
    f1 = t:put(201, 0, "signi_left"), f2 = t:put(201, 0, "signi_center"),
    x = t:put(101, 1, "signi_center"), y = t:put(102, 1, "signi_left"),
  }
end

case("ヤスデス: 세 조건 중 서로 다른 둘. 같은 것을 두 번 고를 수 없다", "WD11-008 FAQ 1", function(t)
  wd(t)
  local c = yasu(t)
  main(t)
  resona(t, c.r)
  t:expect(not has(t:request().options, c.hx), "＜凶蟲＞만")
  t:expect(not t:answer(c.h1, c.h2), "①①")
  t:expect(not t:answer(c.f1, c.f2), "③③")
  t:expect(not t:answer(c.e1, c.e2), "②만")
  t:expect(not t:answer(c.h1, c.e1), "에나는 2장")
  t:expect(not t:answer(c.e1, c.e2, c.e3))
  t:expect(not t:answer(c.h1, c.h2, c.f1))
  t:expect(t:answer(c.h1, c.f1), "①③")
  t:expect(t:wait(HINT_ZONE))
  t:expect(t:answer(t:request().options[1]))
  t:expect(t:wait(HINT_TARGET))
  t:expect(not has(t:request().options, c.y), "레벨 3")
  t:expect(t:answer(c.x))
  t:expect(t:wait(HINT_MAIN))
  t:expect(t:is_in(c.x, 1, "ena") and t:is_in(c.h1, 0, "trash") and t:is_in(c.f1, 0, "trash"))
end)

case("ヤスデス: ①② 또는 ②③으로도 낸다", "WD11-008 출현 조건", function(t)
  wd(t)
