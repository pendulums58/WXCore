-- WXK01-002 アロス・ピルルク　ＴＥＴＲＡ
-- 【常】：あなたの手札が０枚であるかぎり、あなたが対戦相手のルリグによってダメージを受ける場合、代わりにダメージを受けず、ターン終了時まで、この能力を失う。
-- 【起】《ゲーム１回》カタルシス《コインアイコン》：次のあなたのメインフェイズまで、このルリグの基本リミットは１２になりあなたは対戦相手のルリグによってダメージを受けない。あなたが次のあなたのドローフェイズにカードを１枚引く場合、代わりにカードを２枚引く。
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD)
  -- [の間] 【常】 손패 0장인 동안 상대 루리그 대미지 1번을 대신한다(쓰면 이 턴 동안 잃는다: 턴 1번)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_PREVENT_DAMAGE)
  e1:SetRange(LOCATION_LRIG)
  e1:SetTargetRange(1,0)
  e1:SetCountLimit(1)
  e1:SetValue(2)
  e1:SetCondition(function(e) local tp=e:GetHandlerPlayer() return Duel.GetMatchingGroup(nil,tp,LOCATION_HAND,0,nil):GetCount()==0 end)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_IGNITION)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetRange(LOCATION_LRIG)
  e2:SetCountLimit(1,true)
  e2:SetCoinCost(1)
  e2:SetOperation(function(e,tp,eg)
    -- [の間] 「次のあなたのメインフェイズまで」: 다음 내 턴 그로우 페이즈 끝까지(FAQ 2)
    local now=Duel.GetTurnCount()
    local function live() return Duel.GetTurnCount()==now or (Duel.GetTurnCount()==now+1) or (Duel.GetTurnPlayer()==tp and Duel.GetPhase()<PHASE_MAIN) end
    local lc=e:GetHandler()
    local e1=Effect.CreateEffect(lc)
    e1:SetType(EFFECT_TYPE_SINGLE)
    e1:SetCode(EFFECT_UPDATE_LIMIT)
    e1:SetValue(12-11)
    e1:SetCondition(live)
    e1:SetReset(RESET_PHASE+PHASE_END,3)
    lc:RegisterEffect(e1)
    local e2=Effect.CreateEffect(lc)
    e2:SetType(EFFECT_TYPE_FIELD)
    e2:SetCode(EFFECT_NO_LRIG_DAMAGE)
    e2:SetTargetRange(1,0)
    e2:SetCondition(live)
    e2:SetReset(RESET_PHASE+PHASE_END,3)
    Duel.RegisterEffect(e2,tp)
    -- 다음 내 드로 페이즈: 2장이면 4장(FAQ 5). 메인 페이즈에 쓰므로 이 턴 드로 페이즈는 지났다
    local e3=Effect.CreateEffect(lc)
    e3:SetType(EFFECT_TYPE_FIELD)
    e3:SetCode(EFFECT_DRAW_PHASE_DOUBLE)
    e3:SetTargetRange(1,0)
    e3:SetReset(RESET_PHASE+PHASE_END,3)
    Duel.RegisterEffect(e3,tp)
  end)
  c:RegisterEffect(e2)
end
