-- WX02-002 火鳥風月　遊月・肆
-- 【常】：あなたのすべての領域にあるカードは【ライフバースト】【エナチャ―ジ１】を持つ。
-- 【出】：あなたのライフクロス１枚をクラッシュする。
-- 【起】《ダウン》：対戦相手のライフクロス１枚をクラッシュする。
local s,id=GetID()
function s.initial_effect(c)
  local g=Effect.CreateEffect(c)
  g:SetType(EFFECT_TYPE_LIFEBURST)
  g:SetDescription(aux.Ability(id,0))
  g:SetOperation(aux.EnaChargeOp(1))
  -- [の間] 【常】 원래 라이프 버스트가 있는 카드도 하나 더 가진다(FAQ 3)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD)
  e1:SetCode(EFFECT_GRANT_LIFEBURST)
  e1:SetRange(LOCATION_LRIG)
  e1:SetTargetRange(1,0)
  e1:SetValue(1)
  e1:SetLabelObject(g)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_SINGLE+EFFECT_TYPE_TRIGGER_F)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetCode(EVENT_ON_PLAY)
  -- 강제(FAQ 5)
  e2:SetOperation(function(e,tp)
    Duel.Crush(tp,1)
  end)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_IGNITION)
  e3:SetDescription(aux.Ability(id,2))
  e3:SetRange(LOCATION_LRIG)
  e3:SetCost(aux.SelfDownCost)
  e3:SetOperation(function(e,tp)
    Duel.Crush(1-tp,1)
  end)
  c:RegisterEffect(e3)
end
