-- WX12-002 紅蓮乙女　遊月・肆
-- 【自】：対戦相手のアタックフェイズ開始時、あなたのライフクロスが３枚以上ある場合、このターン、あなたはゲームに敗北しない。
-- 【出】：あなたのエナゾーンからすべてのカードをトラッシュに置く。あなたのデッキの一番上のカードをライフクロスに加える。
-- 【起】《ターン１回》《メインフェイズアイコン》《アタックフェイズアイコン》《無》：このターン、あなたのすべての領域にあるカードは【ライフバースト】【エナチャージ１】を持つ。
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EVENT_PHASE_START+PHASE_ATTACK)
  e1:SetRange(LOCATION_LRIG)
  e1:SetCondition(function(e,tp) return Duel.GetTurnPlayer()~=tp end)
  e1:SetOperation(function(e,tp)
    if Duel.GetMatchingGroup(nil,tp,LOCATION_LIFE,0,nil):GetCount()<3 then return end
    -- [の間] 「このターン」(뒤에 라이프가 줄어도. FAQ 2)
    local e1=Effect.CreateEffect(e:GetHandler())
    e1:SetType(EFFECT_TYPE_FIELD)
    e1:SetCode(EFFECT_CANNOT_LOSE)
    e1:SetTargetRange(1,0)
    e1:SetReset(RESET_PHASE+PHASE_END)
    Duel.RegisterEffect(e1,tp)
  end)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_SINGLE+EFFECT_TYPE_TRIGGER_F)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetCode(EVENT_ON_PLAY)
  e2:SetOperation(function(e,tp)
    local g=Duel.GetMatchingGroup(nil,tp,LOCATION_ENA,0,nil)
    if g:GetCount()>0 then Duel.SendToTrash(g,REASON_EFFECT) end
    local d=Duel.GetDecktopGroup(tp,1)
    if d:GetCount()>0 then Duel.SendToLife(d) end
  end)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_IGNITION)
  e3:SetDescription(aux.Ability(id,2))
  e3:SetRange(LOCATION_LRIG)
  e3:SetCountLimit(1)
  e3:SetEnaCost("{C}")
  e3:SetTiming(TIMING_MAIN+TIMING_ATTACK)
  e3:SetOperation(function(e,tp)
    -- [の間] 「このターン」 모든 영역의 카드가 【ライフバースト】【エナチャージ１】을 가진다(이미 가진 카드도 하나 더)
    local lb=Effect.CreateEffect(e:GetHandler())
    lb:SetType(EFFECT_TYPE_LIFEBURST)
    lb:SetOperation(aux.EnaChargeOp(1))
    local e1=Effect.CreateEffect(e:GetHandler())
    e1:SetType(EFFECT_TYPE_FIELD)
    e1:SetCode(EFFECT_GRANT_LIFEBURST)
    e1:SetTargetRange(1,0)
    e1:SetLabelObject(lb)
    e1:SetValue(1)
    e1:SetReset(RESET_PHASE+PHASE_END)
    Duel.RegisterEffect(e1,tp)
  end)
  c:RegisterEffect(e3)
end
