-- WX05-019 コードラビリンス　ルーブル
-- 【常】：このシグニの正面のシグニは能力を失う。　
-- 【常】：対戦相手の場に能力を持たないシグニが２体以上あるかぎり、このシグニのパワーは＋3000される。
-- 【自】：対戦相手のシグニ１体が場からデッキに移動したとき、あなたのデッキから＜迷宮＞のシグニ１枚を探して公開し手札に加え、デッキをシャッフルする。
-- ライフバースト：次のあなたのターンの間、対戦相手の場にあるシグニは能力を失う。カードを１枚引く。
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】 정면의 시그니는 능력을 잃는다(FAQ 1)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_LOSE_ABILITY)
  e1:SetRange(LOCATION_SZONE)
  e1:SetTargetRange(0,LOCATION_SIGNI)
  e1:SetTarget(function(e,x) return x==e:GetHandler():GetFrontCard() end)
  c:RegisterEffect(e1)
  -- [の間] 【常】
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_SINGLE)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetCode(EFFECT_UPDATE_POWER)
  e2:SetRange(LOCATION_SZONE)
  e2:SetCondition(function(e) return Duel.GetMatchingGroup(function(x) return x:IsSigni() and not x:HasAbility() end,e:GetHandlerPlayer(),0,LOCATION_SZONE,nil):GetCount()>=2 end)
  e2:SetValue(3000)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
  e3:SetDescription(aux.Ability(id,2))
  e3:SetCode(EVENT_MOVED_TO_DECK)
  e3:SetRange(LOCATION_SZONE)
  e3:SetCondition(function(e,tp,eg) return eg:Filter(function(x) return x:GetOwner()~=tp and x:IsPreviousLocation(LOCATION_SZONE) end,nil):GetCount()>0 end)
  e3:SetOperation(function(e,tp)
    aux.SearchToHand(tp,function(x) return x:IsSigni() and (x:IsClass(0,RACE_MEIKYU)) end,1)
  end)
  c:RegisterEffect(e3)
  local e4=Effect.CreateEffect(c)
  e4:SetType(EFFECT_TYPE_LIFEBURST)
  e4:SetOperation(function(e,tp)
    -- [の間] 다음 내 턴 동안 상대 장의 시그니(나중에 나온 것도)
    local e1=Effect.CreateEffect(e:GetHandler())
    e1:SetType(EFFECT_TYPE_FIELD)
    e1:SetCode(EFFECT_LOSE_ABILITY)
    e1:SetTargetRange(0,LOCATION_SZONE)
    local now,mine=Duel.GetTurnCount(),Duel.GetTurnPlayer()==tp
    e1:SetCondition(function() return Duel.GetTurnPlayer()==tp and Duel.GetTurnCount()>now end)
    e1:SetReset(RESET_PHASE+PHASE_END,mine and 3 or 2)
    Duel.RegisterEffect(e1,tp)
    Duel.Draw(tp,1)
  end)
  c:RegisterEffect(e4)
end
