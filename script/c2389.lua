-- WX10-010 火銃舞　タマヨリヒメ之参
-- 【常】：このカードの上にグロウするためのコストは《赤×1》《白×1》減る。
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】 이 카드 위에 그로우할 때만(FAQ 1)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_REDUCE_COST)
  e1:SetRange(LOCATION_LRIG)
  e1:SetTargetRange(1,0)
  e1:SetTarget(function(e,x) return x:IsType(TYPE_LRIG) and x:IsLocation(LOCATION_LDECK) end)
  e1:SetEnaCost("{R}")
  e1:SetValue(1)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_FIELD)
  e2:SetDescription(aux.Ability(id,0))
  e2:SetCode(EFFECT_REDUCE_COST)
  e2:SetRange(LOCATION_LRIG)
  e2:SetTargetRange(1,0)
  e2:SetTarget(function(e,x) return x:IsType(TYPE_LRIG) and x:IsLocation(LOCATION_LDECK) end)
  e2:SetEnaCost("{W}")
  e2:SetValue(1)
  c:RegisterEffect(e2)
end
