-- WX16-001 ドーナ　ＦＯＵＲＴＨ
-- 【常】：対戦相手のターンの間、あなたの＜怪異＞のシグニ１体がバニッシュされる場合、代わりにバニッシュされず、ターン終了時まで、この能力を失う。
-- 【出】：あなたのデッキから＜怪異＞のシグニを２枚まで探して公開し手札に加え、デッキをシャッフルする。
-- 【起】エスケープ《アタックフェイズアイコン》《コインアイコン》《コインアイコン》《コインアイコン》：このターン、シグニアタックフェイズをスキップする。
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetAbilityType(ABILITY_CONTINUOUS)
  e1:SetCode(EVENT_PHASE_START+PHASE_UP)
  e1:SetRange(LOCATION_LRIG)
  e1:SetCondition(function(e,tp) return Duel.GetTurnPlayer()~=tp end)
  e1:SetOperation(function(e,tp)
    -- [の間] 상대 턴 동안 ＜怪異＞ 1체의 바니시를 1번 대신한다(쓰면 이 턴 동안 잃는다). 상대 턴 시작에 그 턴용 효과를 건다(근사)
    local e1=Effect.CreateEffect(e:GetHandler())
    e1:SetType(EFFECT_TYPE_FIELD)
    e1:SetCode(EFFECT_BANISH_ONCE)
    e1:SetTargetRange(LOCATION_SZONE,0)
    e1:SetTarget(function(e2,x) return (function(x) return x:IsSigni() and (x:IsClass(0,RACE_KAII)) end)(x) end)
    e1:SetReset(RESET_PHASE+PHASE_END)
    Duel.RegisterEffect(e1,tp)
  end)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_SINGLE+EFFECT_TYPE_TRIGGER_F)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetCode(EVENT_ON_PLAY)
  e2:SetOperation(function(e,tp)
    aux.SearchToHand(tp,function(x) return x:IsSigni() and (x:IsClass(0,RACE_KAII)) end,2)
  end)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_IGNITION)
  e3:SetDescription(aux.Ability(id,2))
  e3:SetRange(LOCATION_LRIG)
  e3:SetCoinCost(3)
  e3:SetTiming(TIMING_ATTACK)
  e3:SetOperation(function(e,tp)
    -- [の間] 「このターン」
    local e1=Effect.CreateEffect(e:GetHandler())
    e1:SetType(EFFECT_TYPE_FIELD)
    e1:SetCode(EFFECT_SKIP_SIGNI_ATTACK)
    e1:SetTargetRange(1,1)
    e1:SetReset(RESET_PHASE+PHASE_END)
    Duel.RegisterEffect(e1,tp)
  end)
  c:RegisterEffect(e3)
end
