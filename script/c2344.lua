-- WX09-019 羅植姫　アキナナ
-- 【常】：このシグニのパワーはあなたのエナゾーンにあるカード１枚につき＋2000される。
-- 【常】：このシグニは自身のパワーが14000以上であるかぎり対戦相手のアーツの効果を受けず、18000以上であるかぎり【ランサー】と「【自】：このシグニがライフクロス１枚をクラッシュしたとき、対戦相手のシグニを２体まで対象とし、それらをバニッシュする。」を得る。
-- 【自】：このシグニのパワーが20000以上になったとき、これをトラッシュに置く。
-- ライフバースト：【エナチャージ１】
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_SINGLE)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_UPDATE_POWER)
  e1:SetRange(LOCATION_SZONE)
  e1:SetValue(function(e) return 2000*Duel.GetMatchingGroup(nil,e:GetHandlerPlayer(),LOCATION_ENA,0,nil):GetCount() end)
  c:RegisterEffect(e1)
  -- [の間] 【常】 파워에 따라(14000 이상 / 18000 이상)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_SINGLE)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetCode(EFFECT_IMMUNE)
  e2:SetRange(LOCATION_SZONE)
  e2:SetCondition(function(e) return e:GetHandler():GetPower()>=14000 end)
  e2:SetValue(function(e,sc,sp) return sp~=e:GetHandlerPlayer() and sc:IsType(TYPE_ARTS) end)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_SINGLE)
  e3:SetDescription(aux.Ability(id,1))
  e3:SetCode(EFFECT_LANCER)
  e3:SetRange(LOCATION_SZONE)
  e3:SetCondition(function(e) return e:GetHandler():GetPower()>=18000 end)
  c:RegisterEffect(e3)
  local e4=Effect.CreateEffect(c)
  e4:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
  e4:SetDescription(aux.Ability(id,1))
  e4:SetAbilityType(ABILITY_CONTINUOUS)
  e4:SetCode(EVENT_CRUSHED)
  e4:SetRange(LOCATION_SZONE)
  e4:SetCondition(function(e,tp,eg,ep) return ep~=tp and Duel.GetCrusher()==e:GetHandler() and e:GetHandler():GetPower()>=18000 end)
  e4:SetTarget(function(e,tp,eg,ep,ev,re,r,rp,chk)
    if chk==0 then return true end
    Duel.SelectTarget(tp,Card.IsSigni,tp,0,LOCATION_SZONE,0,2,nil)
  end)
  e4:SetOperation(function(e,tp)
    local g=Duel.GetTargets():Filter(function(x) return x:IsRelateToEffect(e) end,nil)
    if g:GetCount()>0 then Duel.Banish(g) end
  end)
  c:RegisterEffect(e4)
  local e5=Effect.CreateEffect(c)
  e5:SetType(EFFECT_TYPE_SINGLE)
  e5:SetCode(EFFECT_POWER_WATCH)
  e5:SetRange(LOCATION_SZONE)
  e5:SetValue(20000)
  c:RegisterEffect(e5)
  local e6=Effect.CreateEffect(c)
  e6:SetType(EFFECT_TYPE_SINGLE+EFFECT_TYPE_TRIGGER_F)
  e6:SetDescription(aux.Ability(id,2))
  e6:SetCode(EVENT_POWER_REACHED)
  e6:SetOperation(function(e,tp)
    local h=e:GetHandler()
    if h:IsLocation(LOCATION_SZONE) then Duel.SendToTrash(h,REASON_EFFECT) end
  end)
  c:RegisterEffect(e6)
  local e7=Effect.CreateEffect(c)
  e7:SetType(EFFECT_TYPE_LIFEBURST)
  e7:SetOperation(aux.EnaChargeOp(1))
  c:RegisterEffect(e7)
end
