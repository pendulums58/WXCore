-- WX19-023 弩砲　チタイクウ
-- 【常】：あなたの場に＜アーム＞のシグニがあるかぎり、あなたの＜ウェポン＞のシグニは対戦相手のシグニの効果を受けず、それらのパワーをあなたのターンの間、＋3000する。
-- 【自】《ターン１回》：あなたのセンタールリグがアタックしたとき、そのアタックの間、そのルリグは【ダブルクラッシュ】を得る。
-- 【出】《無》：対戦相手のパワー12000以下のシグニ１体を対象とし、それをバニッシュする。
-- ライフバースト：対戦相手は自分のシグニ１体を対象とし、それをトラッシュに置く。
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】 ＜アーム＞가 있는 동안 ＜ウェポン＞
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_IMMUNE)
  e1:SetRange(LOCATION_SZONE)
  e1:SetTargetRange(LOCATION_SZONE,0)
  e1:SetTarget(function(e,x) return (function(x) return x:IsSigni() and (x:IsClass(0,RACE_WEAPON)) end)(x) end)
  e1:SetCondition(function(e) local tp=e:GetHandlerPlayer() return Duel.GetMatchingGroup(function(x) return x:IsSigni() and (x:IsClass(0,RACE_ARM)) end,tp,LOCATION_SZONE,0,nil):GetCount()>0 end)
  e1:SetValue(function(e,sc,sp) return sp~=e:GetHandlerPlayer() and sc:IsSigni() end)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_FIELD)
  e2:SetDescription(aux.Ability(id,0))
  e2:SetCode(EFFECT_UPDATE_POWER)
  e2:SetRange(LOCATION_SZONE)
  e2:SetTargetRange(LOCATION_SZONE,0)
  e2:SetTarget(function(e,x) return (function(x) return x:IsSigni() and (x:IsClass(0,RACE_WEAPON)) end)(x) end)
  e2:SetCondition(function(e) local tp=e:GetHandlerPlayer() return Duel.GetTurnPlayer()==tp and Duel.GetMatchingGroup(function(x) return x:IsSigni() and (x:IsClass(0,RACE_ARM)) end,tp,LOCATION_SZONE,0,nil):GetCount()>0 end)
  e2:SetValue(3000)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
  e3:SetDescription(aux.Ability(id,1))
  e3:SetCode(EVENT_ATTACK)
  e3:SetRange(LOCATION_SZONE)
  e3:SetCountLimit(1)
  e3:SetCondition(function(e,tp,eg) local x=eg:GetFirst() return x:GetControler()==tp and x:IsType(TYPE_LRIG) end)
  e3:SetOperation(function(e,tp,eg)
    local x=eg:GetFirst()
    if x:IsLocation(LOCATION_LRIG) then aux.GrantKeyword(e,x,EFFECT_DOUBLE_CRUSH) end  -- 「そのアタックの間」은 턴 종료 시까지로 근사
  end)
  c:RegisterEffect(e3)
  local e4=Effect.CreateEffect(c)
  e4:SetType(EFFECT_TYPE_SINGLE+EFFECT_TYPE_TRIGGER_F)
  e4:SetDescription(aux.Ability(id,2))
  e4:SetCode(EVENT_ON_PLAY)
  e4:SetEnaCost("{C}")
  e4:SetTarget(aux.BanishPowerTarget(12000))
  e4:SetOperation(aux.BanishOp)
  c:RegisterEffect(e4)
  local e5=Effect.CreateEffect(c)
  e5:SetType(EFFECT_TYPE_LIFEBURST)
  e5:SetOperation(function(e,tp)
    local tc=Duel.SelectTarget(1-tp,Card.IsSigni,1-tp,LOCATION_SZONE,0,1,1,nil):GetFirst()
    if tc then Duel.SendToTrash(tc,REASON_EFFECT) end
  end)
  c:RegisterEffect(e5)
end
