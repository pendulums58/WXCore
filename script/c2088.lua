-- WX05-025 高尚たる一筆　スイボク
-- 【自】：あなたの＜美巧＞のシグニ１体がバニッシュされたとき、《緑》《白》を支払ってもよい。そうした場合、そのシグニをエナゾーンから場に出す。
-- 【自】：あなたが対戦相手のセンタールリグのアタックを【ガード】するか、対戦相手のシグニのアタックを効果によって無効にしたとき、あなたのデッキの一番上のカードをエナゾーンに置く。
-- ライフバースト：あなたのデッキの一番上のカードをエナゾーンに置く。このターン、次にセンタールリグかシグニがアタックしたとき、そのアタックを無効にする。
local s,id=GetID()
function s.initial_effect(c)
  -- 자신도. 《緑》《白》를 자신으로 내면 나오지 못한다(FAQ 1·2)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EVENT_BANISHED)
  e1:SetRange(LOCATION_SZONE+LOCATION_ENA)
  e1:SetCondition(function(e,tp,eg) local x=eg:GetFirst() return x:GetOwner()==tp and x:IsPreviousLocation(LOCATION_SZONE) and (function(x) return x:IsSigni() and (x:IsClass(0,RACE_BIKOU)) end)(x) end)
  e1:SetOperation(function(e,tp,eg)
    local x=eg:GetFirst()
    if not (x:IsLocation(LOCATION_ENA) and Duel.CanPayEna(tp,"{G}{W}") and Duel.SelectYesNo(tp)) then return end
    Duel.SendToTrash(Duel.SelectEnaCost(tp,"{G}{W}"),REASON_COST)
    if x:IsLocation(LOCATION_ENA) then Duel.PutOnField(x,tp) end
  end)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetCode(EVENT_GUARDED)
  e2:SetRange(LOCATION_SZONE)
  e2:SetCondition(function(e,tp,eg,ep) return ep==tp end)
  e2:SetOperation(aux.EnaChargeOp(1))
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
  e3:SetDescription(aux.Ability(id,1))
  e3:SetCode(EVENT_NEGATED)
  e3:SetRange(LOCATION_SZONE)
  e3:SetCondition(function(e,tp,eg,ep,ev,re,r,rp) return rp==tp and Duel.GetTurnPlayer()~=tp end)
  e3:SetOperation(aux.EnaChargeOp(1))
  c:RegisterEffect(e3)
  local e4=Effect.CreateEffect(c)
  e4:SetType(EFFECT_TYPE_LIFEBURST)
  -- 다음 어택은 누구의 것이든(FAQ 4)
  e4:SetOperation(function(e,tp)
    Duel.EnaCharge(tp,1)
    -- [の間] 「このターン、次に」
    local e1=Effect.CreateEffect(e:GetHandler())
    e1:SetType(EFFECT_TYPE_FIELD)
    e1:SetCode(EFFECT_NEGATE_NEXT_ATTACK)
    e1:SetTargetRange(1,0)
    e1:SetReset(RESET_PHASE+PHASE_END)
    Duel.RegisterEffect(e1,tp)
  end)
  c:RegisterEffect(e4)
end
