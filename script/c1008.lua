-- SPK01-03 幻怪　カマイタチ（パーティーパックVol.1）
-- 【出】《緑》ルリグデッキからアーツ１枚をルリグトラッシュに置く：対戦相手のレベル３以上のシグニ１体を対象とし、それをエナゾーンに置く。
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_SINGLE+EFFECT_TYPE_TRIGGER_F)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EVENT_ON_PLAY)
  e1:SetEnaCost("{G}")
  -- 코스트를 내지 않으면 발동하지 않는다(FAQ 1)
  e1:SetCost(function(e,tp,eg,ep,ev,re,r,rp,chk)
    local g=Duel.GetMatchingGroup(function(x) return x:IsType(TYPE_ARTS) end,tp,LOCATION_LDECK,0,nil)
    if chk==0 then return g:GetCount()>0 end
    Duel.SendToLrigTrash(Duel.SelectCards(tp,g,1,1),REASON_COST)
  end)
  e1:SetTarget(function(e,tp,eg,ep,ev,re,r,rp,chk)
    if chk==0 then return true end
    Duel.SelectTarget(tp,function(x) return x:IsSigni() and x:GetLevel()>=3 end,tp,0,LOCATION_SZONE,1,1,nil)
  end)
  -- 바니시가 아니다(FAQ 3)
  e1:SetOperation(function(e,tp)
    local tc=Duel.GetFirstTarget()
    if tc and tc:IsRelateToEffect(e) then Duel.SendToEna(tc) end
  end)
  c:RegisterEffect(e1)
end
