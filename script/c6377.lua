-- WXK03-001 ピルルク　ＴＥＬＯＳ
-- 【常】：あなたの手札が０枚であるかぎり、あなたはルリグによってダメージを受けない。
-- 【起】《ターン１回》ピーピングアナライズ《コイン×0》：対戦相手の手札を見て１枚選び、捨てさせる。
-- 【起】《ゲーム１回》カタルシス《コイン×0》：対戦相手のセンタールリグ１体を対象とし、このゲームの間、それは「【常】：あなたがドローフェイズにカードを１枚引く場合、代わりに２枚引く。」と「【自】：あなたのターン終了時、手札から無色のカードを１枚捨ててもよい。そうしなかった場合、このルリグはあなたにダメージを与える。」を得る。
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD)
  -- [の間] 【常】 루리그 어택·효과 대미지(근사: 어택 대미지만)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_NO_LRIG_DAMAGE)
  e1:SetRange(LOCATION_LRIG)
  e1:SetTargetRange(1,0)
  e1:SetCondition(function(e) local tp=e:GetHandlerPlayer() return Duel.GetMatchingGroup(nil,tp,LOCATION_HAND,0,nil):GetCount()==0 end)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_IGNITION)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetRange(LOCATION_LRIG)
  e2:SetCountLimit(1)
  e2:SetOperation(function(e,tp,eg)
    local h=Duel.GetMatchingGroup(nil,tp,0,LOCATION_HAND,nil)
    if h:GetCount()==0 then return end
    Duel.ConfirmCards(tp,h)
    Duel.SendToTrash(Duel.SelectCards(tp,h,1,1),REASON_EFFECT+REASON_DISCARD)
  end)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_IGNITION)
  e3:SetDescription(aux.Ability(id,2))
  e3:SetRange(LOCATION_LRIG)
  e3:SetCountLimit(1,true)
  e3:SetOperation(function(e,tp,eg)
    -- 상대 센터가 얻는다. 그로우하면 없어진다(FAQ 4)
    local oc=Duel.GetMatchingGroup(nil,tp,0,LOCATION_LRIG,nil):GetFirst()
    if not oc then return end
    local g1=Effect.CreateEffect(e:GetHandler())
    g1:SetType(EFFECT_TYPE_FIELD)
    g1:SetDescription(aux.Stringid(id,0))
    g1:SetCode(EFFECT_DRAW_PHASE_DOUBLE)
    g1:SetRange(LOCATION_LRIG)
    g1:SetTargetRange(1,0)
    oc:GrantEffect(g1)
    local g2=Effect.CreateEffect(e:GetHandler())
    g2:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
    g2:SetDescription(aux.Stringid(id,1))
    g2:SetCode(EVENT_TURN_END)
    g2:SetRange(LOCATION_LRIG)
    g2:SetCondition(function(e2,tp2) return Duel.GetTurnPlayer()==tp2 end)
    g2:SetOperation(function(e2,tp2)
      local h=Duel.GetMatchingGroup(function(x) return x:GetColor()==0 end,tp2,LOCATION_HAND,0,nil)
      if h:GetCount()>0 and Duel.SelectYesNo(tp2) and Duel.SendToTrash(Duel.SelectCards(tp2,h,1,1),REASON_EFFECT+REASON_DISCARD)>0 then return end
      Duel.Damage(tp2)
    end)
    oc:GrantEffect(g2)
  end)
  c:RegisterEffect(e3)
end
