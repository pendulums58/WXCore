-- WX10-036 大幻蟲　ヴェスパ
-- 【常】：このシグニのレベルは対戦相手の場にある【チャーム】１枚につき１減る。（このシグニは場に出るまでレベル４である）
-- 【常】：このシグニよりレベルの高いシグニがこの正面にあるかぎり、このシグニは【アサシン】を得る。
-- ライフバースト：次のターンの間、あなたの中央のシグニゾーンにあるシグニは、その正面のシグニに【チャーム】が付いているかぎり【アサシン】を得る。
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】 장에서만(괄호)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_SINGLE)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_UPDATE_LEVEL)
  e1:SetRange(LOCATION_SZONE)
  e1:SetValue(function(e) return -(function(p) local n=0 for x in Duel.GetMatchingGroup(Card.IsSigni,p,LOCATION_SZONE,0,nil):Iter() do if x:GetCharm() then n=n+1 end end return n end)(1-e:GetHandlerPlayer()) end)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_SINGLE)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetCode(EFFECT_ASSASSIN)
  e2:SetRange(LOCATION_SZONE)
  e2:SetCondition(function(e) local h=e:GetHandler() local f=h:GetFrontCard() return f and f:GetLevel()>h:GetLevel() end)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_LIFEBURST)
  e3:SetOperation(function(e,tp)
    -- [の間] 「次のターンの間」 나중에 나온 시그니도(FAQ 2)
    local now=Duel.GetTurnCount()
    local e1=Effect.CreateEffect(e:GetHandler())
    e1:SetType(EFFECT_TYPE_FIELD)
    e1:SetCode(EFFECT_ASSASSIN)
    e1:SetTargetRange(LOCATION_SIGNI,0)
    e1:SetTarget(function(e,x) local f=x:GetFrontCard() return x:IsInZone("signi_center") and f and f:GetCharm()~=nil end)
    e1:SetCondition(function() return Duel.GetTurnCount()==now+1 end)
    e1:SetReset(RESET_PHASE+PHASE_END,2)
    Duel.RegisterEffect(e1,tp)
  end)
  c:RegisterEffect(e3)
end
