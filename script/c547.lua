-- SP27-002 幻獣　ダチョウ（セレクターズパック vol.15）
-- 【常】：あなたの場に他の＜空獣＞のシグニがあるかぎり、このシグニのパワーは＋1000され、このシグニは対戦相手のシグニの効果を受けない。
-- 【常】：あなたの場に他の＜地獣＞のシグニがあるかぎり、このシグニのパワーは＋1000され、このシグニは対戦相手のスペルの効果を受けない。
-- 【常】：あなたのセンタールリグが緑であるかぎり、このシグニは「【常】：このシグニの正面のシグニのパワーが15000以上であるかぎり、【アサシン】を得る。」を得る。
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】 2체면 서로 다른 쪽을 본다(FAQ 1)
  local function other(e,race) local h=e:GetHandler() return Duel.GetMatchingGroup(function(x) return x~=h and x:IsSigni() and x:IsClass(0,race) end,e:GetHandlerPlayer(),LOCATION_SZONE,0,nil):GetCount()>0 end
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_SINGLE)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_UPDATE_POWER)
  e1:SetRange(LOCATION_SZONE)
  e1:SetCondition(function(e) return other(e,RACE_KUJU) end)
  e1:SetValue(1000)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_SINGLE)
  e2:SetDescription(aux.Ability(id,0))
  e2:SetCode(EFFECT_IMMUNE)
  e2:SetRange(LOCATION_SZONE)
  e2:SetCondition(function(e) return other(e,RACE_KUJU) end)
  e2:SetValue(function(e,sc,sp) return sp~=e:GetHandlerPlayer() and sc:IsSigni() end)
  c:RegisterEffect(e2)
  -- [の間] 【常】
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_SINGLE)
  e3:SetDescription(aux.Ability(id,1))
  e3:SetCode(EFFECT_UPDATE_POWER)
  e3:SetRange(LOCATION_SZONE)
  e3:SetCondition(function(e) return other(e,RACE_CHIJU) end)
  e3:SetValue(1000)
  c:RegisterEffect(e3)
  local e4=Effect.CreateEffect(c)
  e4:SetType(EFFECT_TYPE_SINGLE)
  e4:SetDescription(aux.Ability(id,1))
  e4:SetCode(EFFECT_IMMUNE)
  e4:SetRange(LOCATION_SZONE)
  e4:SetCondition(function(e) return other(e,RACE_CHIJU) end)
  e4:SetValue(function(e,sc,sp) return sp~=e:GetHandlerPlayer() and sc:IsType(TYPE_SPELL) end)
  c:RegisterEffect(e4)
  -- [の間] 【常】 센터가 초록이면 「正面のシグニのパワーが15000以上であるかぎり【アサシン】」. 정면이 바뀌면 바로 잃는다(FAQ 3)
  local e5=Effect.CreateEffect(c)
  e5:SetType(EFFECT_TYPE_SINGLE)
  e5:SetDescription(aux.Ability(id,2))
  e5:SetCode(EFFECT_ASSASSIN)
  e5:SetRange(LOCATION_SZONE)
  e5:SetCondition(function(e)
    local tp=e:GetHandlerPlayer()
    local lc=Duel.GetMatchingGroup(nil,tp,LOCATION_LRIG,0,nil):GetFirst()
    local f=e:GetHandler():GetFrontCard()
    return lc and lc:IsColor(COLOR_GREEN) and f and f:GetPower()>=15000
  end)
  c:RegisterEffect(e5)
end
