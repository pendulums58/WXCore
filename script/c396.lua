-- PR-K077 紡ぐ鍵（ウィクロスカード大全K-IV＋6th History 付録）
-- 【常】：あなたのセンタールリグは以下の能力を得る。
-- 【起】エクシード１：次のターンの間、対戦相手のルリグはあなたにダメージを与えない。
-- 【起】《アタックフェイズアイコン》エクシード３：ターン終了時まで、あなたのセンタールリグは「【自】：対戦相手のシグニ１体がアタックしたとき、手札からそのシグニと同じレベルのシグニを１枚捨ててもよい。そうした場合、そのアタックしているシグニはこのアタックであなたにダメージを与えない。」を得る。
local s,id=GetID()
function s.initial_effect(c)
  local g1=Effect.CreateEffect(c)
  g1:SetType(EFFECT_TYPE_IGNITION)
  g1:SetDescription(aux.Ability(id,1))
  g1:SetRange(LOCATION_LRIG)
  g1:SetExceedCost(1)
  g1:SetOperation(function(e,tp)
    -- [の間] 次のターンの間
    local now=Duel.GetTurnCount()
    local e1=Effect.CreateEffect(e:GetHandler())
    e1:SetType(EFFECT_TYPE_FIELD)
    e1:SetCode(EFFECT_NO_LRIG_DAMAGE)
    e1:SetTargetRange(1,0)
    e1:SetCondition(function() return Duel.GetTurnCount()==now+1 end)
    e1:SetReset(RESET_PHASE+PHASE_END,2)
    Duel.RegisterEffect(e1,tp)
  end)
  local e91=Effect.CreateEffect(c)
  e91:SetType(EFFECT_TYPE_FIELD)
  -- [の間] 【常】 센터 루리그가 얻는다
  e91:SetDescription(aux.Ability(id,0))
  e91:SetCode(EFFECT_GRANT)
  e91:SetRange(LOCATION_KEY)
  e91:SetTargetRange(LOCATION_LRIG,0)
  e91:SetLabelObject(g1)
  c:RegisterEffect(e91)
  local g2=Effect.CreateEffect(c)
  g2:SetType(EFFECT_TYPE_IGNITION)
  g2:SetDescription(aux.Ability(id,2))
  g2:SetRange(LOCATION_LRIG)
  g2:SetTiming(TIMING_ATTACK)
  g2:SetExceedCost(3)
  g2:SetOperation(function(e,tp)
    local lc=Duel.GetMatchingGroup(nil,tp,LOCATION_LRIG,0,nil):GetFirst()
    if not lc then return end
    local a=Effect.CreateEffect(e:GetHandler())
    a:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
    a:SetDescription(aux.Ability(id,2))
    a:SetCode(EVENT_ATTACK)
    a:SetRange(LOCATION_LRIG)
    a:SetCondition(function(e2,tp2,eg) local x=eg:GetFirst() return x:GetControler()~=tp2 and x:IsSigni() end)
    -- 「このアタックであなたにダメージを与えない」: 다음 대미지 1번 막기로 근사
    a:SetOperation(function(e2,tp2,eg)
      local lv=eg:GetFirst():GetLevel()
      local f=function(x) return x:IsSigni() and x:GetLevel()==lv end
      if Duel.GetMatchingGroup(f,tp2,LOCATION_HAND,0,nil):GetCount()==0 or not Duel.SelectYesNo(tp2) then return end
      Duel.SendToTrash(Duel.SelectDiscard(tp2,1,1,f),REASON_EFFECT+REASON_DISCARD)
      local e1=Effect.CreateEffect(e2:GetHandler())
      e1:SetType(EFFECT_TYPE_FIELD)
      e1:SetCode(EFFECT_PREVENT_DAMAGE)
      e1:SetTargetRange(1,0)
      e1:SetReset(RESET_PHASE+PHASE_END)
      Duel.RegisterEffect(e1,tp2)
    end)
    a:SetReset(RESET_PHASE+PHASE_END)
    lc:GrantEffect(a)
  end)
  local e92=Effect.CreateEffect(c)
  e92:SetType(EFFECT_TYPE_FIELD)
  -- [の間] 【常】 센터 루리그가 얻는다
  e92:SetDescription(aux.Ability(id,0))
  e92:SetCode(EFFECT_GRANT)
  e92:SetRange(LOCATION_KEY)
  e92:SetTargetRange(LOCATION_LRIG,0)
  e92:SetLabelObject(g2)
  c:RegisterEffect(e92)
end
