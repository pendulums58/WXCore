-- WX20-Re18 幻獣　アカズキン
-- 【常】：このシグニのレベルはあなたのエナゾーンにあるカード５枚につき＋１され、このシグニのパワーはこのシグニのレベル１につき＋3000される。
-- 【常】：このシグニはレベルが４以上であるかぎり、「【自】：このシグニがアタックしたとき、このシグニの正面のシグニをバニッシュする。」を得、レベルが５以上であるかぎり、「【常】：このシグニは対戦相手の効果を受けない。」を得る。
-- 【自】：あなたのメインフェイズ開始時、あなたのデッキの一番上のカードをエナゾーンに置く。
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】 레벨은 에나 5장당 ＋1, 파워는 레벨 1당 ＋3000
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_SINGLE)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_UPDATE_LEVEL)
  e1:SetRange(LOCATION_SZONE)
  e1:SetValue(function(e) return math.floor(Duel.GetMatchingGroup(nil,e:GetHandlerPlayer(),LOCATION_ENA,0,nil):GetCount()/5) end)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_SINGLE)
  e2:SetDescription(aux.Ability(id,0))
  e2:SetCode(EFFECT_UPDATE_POWER)
  e2:SetRange(LOCATION_SZONE)
  e2:SetValue(function(e) return 3000*e:GetHandler():GetLevel() end)
  c:RegisterEffect(e2)
  local g=Effect.CreateEffect(c)
  g:SetType(EFFECT_TYPE_SINGLE+EFFECT_TYPE_TRIGGER_F)
  g:SetCode(EVENT_ATTACK)
  g:SetOperation(function(e,tp)
    local f=Duel.GetFrontZone(e:GetHandler():GetZone())
    local x=Duel.GetMatchingGroup(function(c) return c:IsSigni() and c:GetZone()==f end,tp,0,LOCATION_SZONE,nil):GetFirst()
    if x then Duel.Banish(x) end
  end)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_SINGLE)
  e3:SetDescription(aux.Ability(id,1))
  e3:SetCode(EFFECT_GRANT)
  e3:SetRange(LOCATION_SZONE)
  e3:SetCondition(function(e) return e:GetHandler():GetLevel()>=4 end)
  e3:SetLabelObject(g)
  c:RegisterEffect(e3)
  local e4=Effect.CreateEffect(c)
  e4:SetType(EFFECT_TYPE_SINGLE)
  e4:SetDescription(aux.Ability(id,1))
  e4:SetCode(EFFECT_IMMUNE)
  e4:SetRange(LOCATION_SZONE)
  e4:SetCondition(function(e) return e:GetHandler():GetLevel()>=5 end)
  e4:SetValue(function(e,sc,sp) return sp~=e:GetHandlerPlayer() end)
  c:RegisterEffect(e4)
  local e5=Effect.CreateEffect(c)
  e5:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
  e5:SetDescription(aux.Ability(id,2))
  e5:SetCode(EVENT_PHASE_START+PHASE_MAIN)
  e5:SetRange(LOCATION_SZONE)
  e5:SetCondition(function(e,tp) return Duel.GetTurnPlayer()==tp end)
  e5:SetOperation(aux.EnaChargeOp(1))
  c:RegisterEffect(e5)
end
