-- SP38-008 轟炎　花代・爾転（「ウィクロス 10th Anniversary Book」付録）
-- 【常】：あなたのグロウフェイズをスキップする。
-- 【常】《自分ターン》：あなたの中央のシグニゾーンにあるシグニのパワーを＋5000する。
-- 【起】《ゲーム１回》《赤》《赤》《赤》：このターン、次にこのルリグがアタックしたとき、そのアタックの間、対戦相手は【ガード】ができない。
local s,id=GetID()
function s.initial_effect(c)
  -- [の間] 【常】 효과로 그로우하는 것은 된다(FAQ 1)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_SKIP_GROW)
  e1:SetRange(LOCATION_LRIG)
  e1:SetTargetRange(1,0)
  c:RegisterEffect(e1)
  -- [の間] 【常】
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_FIELD)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetCode(EFFECT_UPDATE_POWER)
  e2:SetRange(LOCATION_LRIG)
  e2:SetTargetRange(LOCATION_SZONE,0)
  e2:SetTarget(function(e,x) return x:IsSigni() and x:IsInZone("signi_center") end)
  e2:SetCondition(function(e) return Duel.GetTurnPlayer()==e:GetHandlerPlayer() end)
  e2:SetValue(5000)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_IGNITION)
  e3:SetDescription(aux.Ability(id,2))
  e3:SetRange(LOCATION_LRIG)
  e3:SetCountLimit(1,true)
  e3:SetEnaCost("{R}{R}{R}")
  e3:SetOperation(function(e,tp)
    -- [の間] 「このターン、次にこのルリグがアタックしたとき、そのアタックの間」
    local h=e:GetHandler()
    local e1=Effect.CreateEffect(h)
    e1:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_TRIGGER_F)
    e1:SetCode(EVENT_ATTACK)
    e1:SetCountLimit(1)
    e1:SetCondition(function(e2,tp2,eg) return eg:GetFirst()==h end)
    e1:SetOperation(function()
      local e2=Effect.CreateEffect(h)
      e2:SetType(EFFECT_TYPE_FIELD)
      e2:SetCode(EFFECT_NO_GUARD)
      e2:SetTargetRange(0,1)
      e2:SetReset(RESET_PHASE+PHASE_END)
      Duel.RegisterEffect(e2,tp)
    end)
    e1:SetReset(RESET_PHASE+PHASE_END)
    Duel.RegisterEffect(e1,tp)
  end)
  c:RegisterEffect(e3)
end
