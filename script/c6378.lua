-- WXK03-002 カーニバル　†ＭＡＩＳ†
-- 【常】：対戦相手のエナゾーンにあるカードは【マルチエナ】を失う。
-- 【出】：シグニのカード名１つを宣言する。このゲームの間、対戦相手の場にある宣言されたカード名のカードは《サーバント ＺＥＲＯ》になる。
-- 【起】《ゲーム１回》ジョーカー《コイン×0》：あなたのルリグデッキにクラフトの《落華流粋》１枚を加える。このゲームの間、あなたの《落華流粋》の使用コストは《黒×2》《無×1》になる。
local s,id=GetID()
function s.initial_effect(c)
  local e1=Effect.CreateEffect(c)
  e1:SetType(EFFECT_TYPE_FIELD)
  -- [の間] 【常】 뒤에 얻는 것도 잃는다(근사: FAQ 1은 나온 순서로 정한다)
  e1:SetDescription(aux.Ability(id,0))
  e1:SetCode(EFFECT_LOSE_KEYWORD)
  e1:SetRange(LOCATION_LRIG)
  e1:SetTargetRange(0,LOCATION_ENA)
  e1:SetValue(EFFECT_MULTI_ENA)
  c:RegisterEffect(e1)
  local e2=Effect.CreateEffect(c)
  e2:SetType(EFFECT_TYPE_SINGLE+EFFECT_TYPE_TRIGGER_F)
  e2:SetDescription(aux.Ability(id,1))
  e2:SetCode(EVENT_ON_PLAY)
  e2:SetOperation(function(e,tp,eg)
    local cid=Duel.AnnounceCard(tp)
    -- [の間] 「このゲームの間」 장에 있는 동안. 이 루리그가 떠나도 남는다(FAQ 6)
    local z=Effect.CreateEffect(e:GetHandler())
    z:SetType(EFFECT_TYPE_FIELD)
    z:SetCode(EFFECT_LOSE_ABILITY)
    z:SetTargetRange(0,LOCATION_SZONE)
    z:SetTarget(function(e2,x) return x:GetOriginalCode()==cid end)
    Duel.RegisterEffect(z,tp)
    local z=Effect.CreateEffect(e:GetHandler())
    z:SetType(EFFECT_TYPE_FIELD)
    z:SetCode(EFFECT_SET_BASE_POWER)
    z:SetTargetRange(0,LOCATION_SZONE)
    z:SetTarget(function(e2,x) return x:GetOriginalCode()==cid end)
    z:SetValue(1000)
    Duel.RegisterEffect(z,tp)
    local z=Effect.CreateEffect(e:GetHandler())
    z:SetType(EFFECT_TYPE_FIELD)
    z:SetCode(EFFECT_CHANGE_LEVEL)
    z:SetTargetRange(0,LOCATION_SZONE)
    z:SetTarget(function(e2,x) return x:GetOriginalCode()==cid end)
    z:SetValue(1)
    Duel.RegisterEffect(z,tp)
  end)
  c:RegisterEffect(e2)
  local e3=Effect.CreateEffect(c)
  e3:SetType(EFFECT_TYPE_IGNITION)
  e3:SetDescription(aux.Ability(id,2))
  e3:SetRange(LOCATION_LRIG)
  e3:SetCountLimit(1,true)
  e3:SetOperation(function(e,tp,eg)
    Duel.AddCraft(6456,tp)
    -- [の間] 「このゲームの間」 크래프트가 아닌 《落華流粋》도(FAQ 3)
    local e1=Effect.CreateEffect(e:GetHandler())
    e1:SetType(EFFECT_TYPE_FIELD)
    e1:SetCode(1006456)
    e1:SetTargetRange(1,0)
    Duel.RegisterEffect(e1,tp)
  end)
  c:RegisterEffect(e3)
end
